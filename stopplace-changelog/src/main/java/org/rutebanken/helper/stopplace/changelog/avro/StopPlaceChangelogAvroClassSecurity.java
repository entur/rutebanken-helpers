package org.rutebanken.helper.stopplace.changelog.avro;

import org.apache.avro.util.ClassSecurityValidator;
import org.rutebanken.irkalla.avro.EnumType;
import org.rutebanken.irkalla.avro.StopPlaceChangelogEvent;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Declares the Avro classes generated from {@code src/main/avro} as trusted Avro classes.
 *
 * <p>Since Avro 1.12.2, {@link ClassSecurityValidator} guards every class that Avro resolves by
 * name and trusts only a handful of JDK types by default. The Kafka consumer is configured with
 * {@code specific.avro.reader=true}, so the Confluent {@code KafkaAvroDeserializer} resolves the
 * reader class from the writer schema name. Without this registration every poll fails with
 * {@code SecurityException: Forbidden org.rutebanken.irkalla.avro.StopPlaceChangelogEvent!}.
 *
 * <p>The global validator is always composed from {@link ClassSecurityValidator#DEFAULT} rather
 * than from the current global instance. This keeps the Avro defaults (the JDK types and the
 * {@code org.apache.avro.SERIALIZABLE_CLASSES} / {@code org.apache.avro.SERIALIZABLE_PACKAGES}
 * system properties, which remain available as an operational override), and it makes the
 * registration idempotent: repeated calls cannot build up an ever deeper chain of nested
 * validators.
 *
 * <p>The stopplace-changelog-starter invokes {@link #trustGeneratedClasses()} automatically.
 * Applications that use this core module without the starter must call it themselves before the
 * first record is deserialized.
 */
public final class StopPlaceChangelogAvroClassSecurity {

  private static final Logger LOGGER = LoggerFactory.getLogger(
    StopPlaceChangelogAvroClassSecurity.class
  );

  /**
   * The Avro classes generated by the avro-maven-plugin from {@code src/main/avro}.
   * Enums and fixed types are resolved by name as well, so every named type in the schema must
   * be declared here. A new named type added to the schema must be declared here too.
   */
  private static final ClassSecurityValidator.ClassSecurityPredicate GENERATED_CLASSES =
    ClassSecurityValidator
      .builder()
      .add(StopPlaceChangelogEvent.class)
      .add(EnumType.class)
      .build();

  private StopPlaceChangelogAvroClassSecurity() {}

  /**
   * Installs the Avro class security validator that trusts the generated stop place changelog
   * classes in addition to the Avro defaults.
   */
  public static void trustGeneratedClasses() {
    ClassSecurityValidator.setGlobal(
      ClassSecurityValidator.composite(
        ClassSecurityValidator.DEFAULT,
        GENERATED_CLASSES
      )
    );
    LOGGER.info(
      "Registered {} and {} as trusted Avro classes",
      StopPlaceChangelogEvent.class.getName(),
      EnumType.class.getName()
    );
  }
}
